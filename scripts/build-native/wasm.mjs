/**
 * The engine as WebAssembly (wasm32-wasi, a reactor): what `@hzblj/nitro-crypto/testing` runs in Node, so the
 * TypeScript tests and an adapter's own tests exercise the same Zig code the phones run, without a device.
 * It imports one function, `wasi_snapshot_preview1.random_get`.
 *
 * Besides engine/wasm/, the binary is written into the package's source as base64
 * (src/host/wasm-binary.generated.ts): the testing entry then needs no file system, no `import.meta` and no
 * bundler support, so it loads the same way under Node, Jest's CommonJS and Vitest.
 */
import {cpSync, readFileSync, writeFileSync} from 'node:fs'
import path from 'node:path'

import {ENGINE_OUTPUT, ENGINE_SOURCE, freshDirectory, log, ROOT, run, sha256} from './shared.mjs'

const GENERATED = path.join(ROOT, 'packages/nitro-crypto/src/host/wasm-binary.generated.ts')

export const buildWasm = () => {
  run('zig', ['build', 'wasm'], {cwd: ENGINE_SOURCE})
  const destination = path.join(freshDirectory(path.join(ENGINE_OUTPUT, 'wasm')), 'nitro_crypto.wasm')
  cpSync(path.join(ENGINE_SOURCE, 'zig-out/bin/nitro_crypto.wasm'), destination)
  writeFileSync(
    GENERATED,
    [
      '// Generated by scripts/build-native/wasm.mjs (`yarn engine:wasm`). Do not edit.',
      `// The engine as wasm32-wasi, SHA-256 ${sha256(destination)}.`,
      `export const ENGINE_WASM_BASE64 = '${readFileSync(destination).toString('base64')}'`,
      '',
    ].join('\n')
  )
  log('built wasm32-wasi')
  return [destination]
}
